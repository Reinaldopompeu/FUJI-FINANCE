ROOT = Path(__file__).resolve().parents[1]
URL = os.getenv('POSTGRES_TEST_URL')


@unittest.skipUnless(URL, 'PostgreSQL de teste não configurado')
class PostgreSQLDeploymentTest(unittest.TestCase):
    def test_upgrade_write_permissions_and_user_isolation(self):
        self.run_upgrade('VARCHAR(20)', "'legado'")

    def test_legacy_serial_ids_and_foreign_keys(self):
        self.run_upgrade('SERIAL', '42')

    def test_legacy_identity_ids_and_foreign_keys(self):
        self.run_upgrade('INTEGER GENERATED BY DEFAULT AS IDENTITY', '42')

    def run_upgrade(self, bank_type, bank_id):
        params = conninfo_to_dict(URL)
        self.assertEqual(params.get('dbname'), 'caixa_test')
        self.assertIn(params.get('host'), ('localhost', '127.0.0.1'))
        name = 'caixa_test_' + uuid.uuid4().hex
